#!/usr/bin/env node
/**
 * Generates src/app/core/data-manifest.ts -- every served file under data/,
 * mapped to the first 8 hex characters of its SHA-256.
 *
 * Two properties are load-bearing, because CI regenerates this file and fails
 * on any diff (see the "data manifest is up to date" step in ci.yml):
 *
 *   - Output is deterministic. Keys are sorted as whole paths, not per
 *     directory, so the same tree always produces the same file. (Per-directory
 *     sorting is not enough: '.' sorts before '/', so a global sort puts
 *     'icons.json' ahead of 'icons/Abs.png' while a walk emits it after.)
 *   - Output is NOT Prettier-formatted, and the file is in .prettierignore.
 *     `npm run format` would otherwise rewrite it and break the check.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const DATA = join(here, '..', 'data');
const OUT = join(here, '..', 'src', 'app', 'core', 'data-manifest.ts');

/**
 * Never served: build inputs that happen to live under data/ -- star_noise is a
 * render input for tools/planet_render.py, meshes.json a build input for
 * scripts/gen-circuits.ts. Kept in step with angular.json's asset `ignore`.
 */
const EXCLUDE = new Set(['star_noise', 'meshes.json']);

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    if (dir === DATA && EXCLUDE.has(name)) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(p);
  }
  return out;
}

const entries = walk(DATA)
  .map((p) => [
    relative(DATA, p).split(sep).join('/'),
    createHash('sha256').update(readFileSync(p)).digest('hex').slice(0, 8),
  ])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

const body = entries.map(([k, v]) => `  '${k}': '${v}',`).join('\n');

writeFileSync(
  OUT,
  `// GENERATED by scripts/gen-data-manifest.mjs -- do not edit.
//
// Content hashes for everything under data/. DataService appends these as
// ?v=<hash> so nginx can serve the files immutable; see docker/nginx.conf's
// $data_cache_control map.
export const DATA_MANIFEST: Record<string, string> = {
${body}
};
`,
);

/**
 * The preload block in src/index.html.
 *
 * Same hashes, one source: a preload naming a stale ?v= is a file downloaded
 * twice, which is worse than not preloading it at all. `as="fetch"` with
 * `crossorigin` is what HttpClient's own request matches -- get that wrong
 * and the browser fetches each file a second time rather than reusing the
 * preloaded one.
 */
const INDEX = join(here, '..', 'src', 'index.html');
const PRELOAD = [
  'components_full.json',
  'planets.json',
  'objectives.json',
  'icons.json',
  'stat_labels.json',
];

const missing = PRELOAD.filter((f) => !Object.fromEntries(entries)[f]);
if (missing.length) {
  throw new Error(`gen-data-manifest: no hash for ${missing.join(', ')} -- is data/ complete?`);
}

const byPath = Object.fromEntries(entries);
const links = PRELOAD.map(
  (f) => `    <link rel="preload" as="fetch" crossorigin href="data/${f}?v=${byPath[f]}" />`,
).join('\n');

const html = readFileSync(INDEX, 'utf8');
const begin = html.indexOf('<!-- BEGIN generated by scripts/gen-data-manifest.mjs');
const endMark = '<!-- END generated -->';
const end = html.indexOf(endMark);
if (begin === -1 || end === -1) {
  throw new Error('gen-data-manifest: index.html has no BEGIN/END generated block');
}
const head = html.slice(0, html.indexOf('-->', begin) + 3);
writeFileSync(INDEX, `${head}\n${links}\n    ${html.slice(end)}`);

console.log(`data-manifest.ts: ${entries.length} entries, ${PRELOAD.length} preloads`);
